// Hidden local engine manager: starts/stops the portable ComfyUI that executes
// local models (MiniMax H3). It runs windowless, bound to 127.0.0.1, with no
// browser; the studio is the only user interface.
import { spawn } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';

export function createEngineManager({ getSettings, configDir }) {
  let child = null;
  const paths = () => {
    const dir = getSettings().engine_dir ?? 'C:\\Users\\harry\\Downloads\\H3 Engine';
    const portable = path.join(dir, 'ComfyUI_windows_portable');
    return {
      dir,
      python: path.join(portable, 'python_embeded', 'python.exe'),
      main: path.join(portable, 'ComfyUI', 'main.py'),
      extra: path.join(configDir, 'extra_model_paths.yaml'),
      log: path.join(configDir, 'engine.log'),
    };
  };
  const url = () => (getSettings().url ?? 'http://127.0.0.1:8188').replace(/\/+$/, '');

  async function status() {
    const p = paths();
    const installed = fs.existsSync(p.python) && fs.existsSync(p.main);
    try {
      const r = await fetch(url() + '/system_stats', { signal: AbortSignal.timeout(2000) });
      const s = await r.json();
      const d = s.devices?.[0];
      return { installed, running: true, managed: !!child, comfyui: s.system?.comfyui_version, gpu: d?.name, vram_gb: d ? +(d.vram_total / 2 ** 30).toFixed(1) : null, vram_free_gb: d ? +(d.vram_free / 2 ** 30).toFixed(1) : null };
    } catch { return { installed, running: false, managed: !!child }; }
  }

  async function start() {
    const p = paths();
    if (!fs.existsSync(p.python)) throw Object.assign(new Error(`engine not installed at ${p.dir}`), { status: 409 });
    if ((await status()).running) return status();
    const port = new URL(url()).port || '8188';
    writeModelPaths(p);
    const out = fs.openSync(p.log, 'a');
    child = spawn(p.python, ['-s', p.main, '--listen', '127.0.0.1', '--port', port, '--disable-auto-launch', '--extra-model-paths-config', p.extra],
      { cwd: path.dirname(p.main), windowsHide: true, detached: false, stdio: ['ignore', out, out] });
    child.on('exit', () => { child = null; });
    for (let i = 0; i < 600; i++) { // cold start from a USB HDD took > 5 min (Python imports + CUDA init)
      await new Promise((r) => setTimeout(r, 1000));
      if ((await status()).running) return status();
      if (!child) break;
    }
    throw Object.assign(new Error(`engine did not come up — see ${p.log}`), { status: 502 });
  }

  // ComfyUI model-path config pointing at <engine_dir>/models (regenerated on every start).
  function writeModelPaths(p) {
    fs.mkdirSync(configDir, { recursive: true });
    const base = path.join(p.dir, 'models').split(path.sep).join('/') + '/';
    fs.writeFileSync(p.extra, `# Generated by Harry AI FILM STUDIO
h3_engine:
    base_path: ${base}
    diffusion_models: diffusion_models/
    text_encoders: text_encoders/
    vae: vae/
    loras: loras/
`);
  }

  // Only stops an engine this studio started.
  function stop() { if (child) { child.kill(); child = null; } return { stopped: true }; }

  return { status, start, stop, paths };
}
